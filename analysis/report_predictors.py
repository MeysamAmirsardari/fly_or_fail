"""Render the RESULTS block of analysis/PREDICTORS.md from out/predictors_<ver>_summary.json (+ tables)."""
import json, os, sys
import numpy as np, pandas as pd
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import common as C

L = []
w = L.append


def fmt(x, nd=3):
    if x is None: return 'NA'
    if isinstance(x, float):
        if x != 0 and (abs(x) < 1e-3 or abs(x) >= 1e5): return f'{x:.2e}'
        return f'{x:.{nd}f}'
    return str(x)


w('## R. Results (generated by `report_predictors.py`)\n')
for ver in ('v783', 'v630'):
    p = C.OUT + f'predictors_{ver}_summary.json'
    if not os.path.exists(p): w(f'*{ver}: not yet computed.*\n'); continue
    sm = json.load(open(p))
    df = pd.read_parquet(C.OUT + f'predictors_{ver}.parquet')
    l0 = sm['L0']; b = l0['betweenness']
    w(f'### {ver}\n')
    w(f'- Rows: {len(df)} neurons (union of the intact closures for S_shiu and S_pure, plus S and both MN9s); '
      f'{df.shape[1]} columns.')
    w(f'- L0: PageRank power iteration {l0["pagerank_power_iters"]} iterations; igraph vs power on a 20k-node subgraph: '
      f'max |Δ| = {fmt(l0["pagerank_igraph_vs_power_subgraph20k_maxabs"])} (max relative {fmt(l0["pagerank_igraph_vs_power_subgraph20k_max_rel"])}). '
      f'Betweenness: k = {b["k_per_replicate"]} sources × 2 replicates (seeds {b["seeds"]}); Spearman(rep1, rep2) over rows = '
      f'{fmt(b["spearman_rep1_rep2_rows"])}, over all neurons = {fmt(b["spearman_rep1_rep2_all"])}; median relative SE '
      f'(rows with B > 0) = {fmt(b["median_rel_se_rows_nonzero"])}; var(rep1 − rep2)/var(B) over rows = {fmt(b["rel_var_rep_diff_rows"])}. '
      f'L0 wall time {l0["wall_s"]} s.\n')
    w('| input_readout | LIN-S corridor n / ρ(Ŵ) / α | LIN-S f_S (all S) / Σ f_GRN / f_T | LIN-S GMRES max\\|Δf\\| (n) / pair / types max | '
      'MF-S corridor n / MF / f_S / Σ f_GRN | λ50 (Hz) / O_max | LIN-A n / ρ(A) / D<0 | LIN-A f_S / Σ f_GRN / f_T | LIN-A SM vs direct / identity / padding | '
      'MF-A n / f_S | walks (L ≤ 5) |')
    w('|' + '---|' * 11)
    for tag, ck in sm['checks'].items():
        ls = ck['LIN_S']; v = ls['verification']; ms = ck['MF_S']
        tmax = max([val for k, val in v.items() if k.startswith('type_')] or [0.0])
        l2 = ck.get('L2') or {}
        la = l2.get('LIN_A', {}); ma = l2.get('MF_A', {})
        w(f'| {tag} | {ls["n_nodes"]} / {fmt(ls["rho_What"], 4)} / {fmt(ls["alpha"], 4)} | {fmt(ls["f_S_all"], 12)} / {fmt(ls["sum_f_GRN"], 12)} / {fmt(ls["f_T"], 5)} | '
          f'{fmt(v["max_abs_f_diff"])} ({v["n_checked"]}) / {fmt(v["pair_woodbury_vs_gmres_absdiff"])} / {fmt(tmax)} | '
          f'{ms["n_nodes"]} / {ms["MF"]} / {fmt(ms["f_S_all"], 6)} / {fmt(ms["sum_f_GRN"])} | '
          f'{fmt(la.get("lam50"), 3)} / {fmt(la.get("Omax"), 2)} | {la.get("n_nodes")} / {fmt(la.get("rho_A"), 4)} / {la.get("n_D_neg")} | '
          f'{fmt(la.get("f_S_all"), 12)} / {fmt(la.get("sum_f_GRN"), 12)} / {fmt(la.get("f_T"), 5)} | '
          f'{fmt(la.get("verify_SM_vs_direct_maxabs"))} / {fmt(la.get("verify_linear_response_identity_maxabs"))} / '
          f'{fmt(la.get("verify_padding_inactive_active_maxabs"))}, {fmt(la.get("verify_padding_inactive_f_maxabs"))} | '
          f'{ma.get("n_nodes")} / {fmt(ma.get("f_S_all"), 6)} | {ck["walks_total_L5"]} |')
    w('')
    w('**Cuts / dominators** (T excluded; "active" also excludes GRNs):\n')
    w('| input_readout | whole-brain unsigned | whole-brain excitatory | exc corridor L5 | exc active at λ50 | 3-way agreement (corridor, active) | κ (active) / #min cuts / complete / #nodes in some min cut |')
    w('|---|---|---|---|---|---|---|')
    for tag, ck in sm['checks'].items():
        l2 = (ck.get('L2') or {}).get('MF_A', {})
        da = l2.get('dominators_active', [])
        dty = l2.get('dominators_active_types', [])
        w(f'| {tag} | {len(ck["dominators_all"]["ids"])} {ck["dominators_all"]["ids"]} | {len(ck["dominators_exc"]["ids"])} {ck["dominators_exc"]["ids"]} | '
          f'{len(ck["MF_S"]["corridor_dominators"]["igraph"])} | {len(da)} {list(zip(da, dty))} | '
          f'{ck["MF_S"]["corridor_dominators"]["agree_igraph_networkx_mf"]}, {l2.get("dominators_agree_igraph_networkx_mf")} '
          f'(whole-brain path-BFS check: {ck["dominators_all"]["mf_agree"]}, {ck["dominators_exc"]["mf_agree"]}) | '
          f'{l2.get("kappa_min_vertex_cut")} / {l2.get("n_min_cuts")} / {l2.get("min_cut_enumeration_complete")} / {l2.get("n_nodes_in_some_min_cut")} |')
    w('')
    w('**Negative control** (rows with no S→T path; all f columns must be exactly 0):\n')
    for tag, ck in sm['checks'].items():
        nc = ck['negative_control']
        mx = max(list(nc['max_abs_f_no_path'].values()) + [0.0])
        mxe = max(list(nc['max_abs_fMF_no_exc_path'].values()) + [0.0])
        w(f'- {tag}: {nc["n_rows_no_ST_path"]} rows without any S→T path, max |f| = {fmt(mx)}; '
          f'{nc["n_rows_no_exc_ST_path"]} rows without an excitatory S→T path, max |f^MF| = {fmt(mxe)}; '
          f'candidates (active at some λ, not S/T): {ck["n_candidates_active_nonS_nonT"]}.')
    w('')
    w('**GRN shares** (positive control: each GRN\'s f vs its share; Σ_s f^LIN_s = 1 by construction):\n')
    for tag, ck in sm['checks'].items():
        g1 = np.array(list(ck['LIN_S']['GRN_f'].values()))
        la = (ck.get('L2') or {}).get('LIN_A', {})
        g2 = np.array(list(la.get('GRN_f', {}).values())) if la else np.array([np.nan])
        w(f'- {tag}: f^LIN-S per GRN min/median/max = {fmt(g1.min())}/{fmt(np.median(g1))}/{fmt(g1.max())} (1/|S| = {fmt(1/len(g1))}); '
          f'Spearman with GRN out-strength = {fmt(ck["LIN_S"]["GRN_f_vs_outstrength_spearman"])}; '
          f'f^LIN-A per GRN min/median/max = {fmt(np.nanmin(g2))}/{fmt(np.nanmedian(g2))}/{fmt(np.nanmax(g2))}; '
          f'measured r_GRN/λ50 = {fmt(la.get("GRN_rate_over_lambda50"))}; Σ f^MF-S_GRN = {fmt(ck["MF_S"]["sum_f_GRN"])}.')
    w('')
p = C.OUT + 'external_types_structural.csv'
if os.path.exists(p):
    e = pd.read_csv(p)
    w('### External types (set-level structural fractions; `out/external_types_structural.csv`)\n')
    cols = ['ver', 'input', 'readout', 'type', 'n_present', 'fLIN_S', 'fMF_S', 'fLIN_A', 'fMF_A', 'n_in_LIN_S_corridor', 'n_in_active_LIN']
    t = e[cols].round(4)
    w('| ' + ' | '.join(cols) + ' |'); w('|' + '---|' * len(cols))
    for r in t.itertuples(index=False): w('| ' + ' | '.join(str(x) for x in r) + ' |')
    w('')
open(C.ROOT + 'out/predictors_results_block.md', 'w').write('\n'.join(L))
doc = open(C.ROOT + 'PREDICTORS.md').read()
a = doc.index('<!--RESULTS-->')
b = doc.index('<!--/RESULTS-->') + len('<!--/RESULTS-->') if '<!--/RESULTS-->' in doc else a + len('<!--RESULTS-->')
doc = doc[:a] + '<!--RESULTS-->\n' + '\n'.join(L) + '\n<!--/RESULTS-->' + doc[b:]
open(C.ROOT + 'PREDICTORS.md', 'w').write(doc)
print('\n'.join(L))
